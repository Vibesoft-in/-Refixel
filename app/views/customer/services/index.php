<script>
document.addEventListener('DOMContentLoaded', function () {
  var sidebarCol          = document.getElementById('servicesSidebarCol');
  var backdrop            = document.getElementById('sidebarBackdrop');
  var openBtn             = document.getElementById('mobileFilterBtn');
  var closeBtn            = document.getElementById('sidebarCloseBtn');
  var sidebarLinks        = document.querySelectorAll('.cat-sidebar-link');
  var headerBlock         = document.getElementById('serviceCatalogueHeader');
  var allCategoriesGrid   = document.getElementById('categoriesGrid');
  var packagesContainer   = document.getElementById('categoryPackagesContainer');
  var contentCol          = document.getElementById('servicesContentCol');

  // Category slug to URL map for seamless browser navigation
  var categoryUrls = {
    'all': '<?= \App\Core\View::url('/services') ?>'
    <?php foreach ($categories ?? [] as $c): ?>
      ,'<?= \App\Core\View::e($c['slug']) ?>': '<?= \App\Core\View::url("/{$c['slug']}-services-in-{$citySlug}") ?>'
    <?php endforeach; ?>
  };

  /* ── Open / Close helpers for mobile ── */
  function openSidebar() {
    if (sidebarCol) sidebarCol.classList.add('is-open');
    if (backdrop) backdrop.classList.add('is-open');
    document.body.style.overflow = 'hidden';
  }

  function closeSidebar() {
    if (sidebarCol) sidebarCol.classList.remove('is-open');
    if (backdrop) backdrop.classList.remove('is-open');
    document.body.style.overflow = '';
  }

  if (openBtn)  openBtn.addEventListener('click', openSidebar);
  if (closeBtn) closeBtn.addEventListener('click', closeSidebar);
  if (backdrop) backdrop.addEventListener('click', closeSidebar);

  /* ── Switch Category Function (Zero reload, zero sidebar re-render) ── */
  function switchCategory(catSlug, updateHistory) {
    if (typeof updateHistory === 'undefined') updateHistory = true;

    // 1. Update active class on sidebar links
    sidebarLinks.forEach(function (l) {
      if (l.getAttribute('data-filter') === catSlug) {
        l.classList.add('active');
      } else {
        l.classList.remove('active');
      }
    });

    // 2. Switch Right Content Area
    if (catSlug === 'all') {
      if (headerBlock) headerBlock.style.display = '';
      if (allCategoriesGrid) allCategoriesGrid.style.display = '';
      if (packagesContainer) packagesContainer.style.display = 'none';

      if (updateHistory && window.history && window.history.pushState) {
        var allUrl = categoryUrls['all'] || '<?= \App\Core\View::url('/services') ?>';
        window.history.pushState({ category: 'all' }, '', allUrl);
      }
    } else {
      if (headerBlock) headerBlock.style.display = 'none';
      if (allCategoriesGrid) allCategoriesGrid.style.display = 'none';
      if (packagesContainer) packagesContainer.style.display = '';

      var allViews = document.querySelectorAll('.category-packages-view');
      allViews.forEach(function (view) {
        if (view.getAttribute('data-category') === catSlug) {
          view.style.display = '';
        } else {
          view.style.display = 'none';
        }
      });

      if (updateHistory && window.history && window.history.pushState) {
        var targetUrl = categoryUrls[catSlug] || ('<?= \App\Core\View::url('/') ?>' + catSlug + '-services-in-<?= $citySlug ?>');
        window.history.pushState({ category: catSlug }, '', targetUrl);
      }
    }

    // 3. Scroll positioning: if user has scrolled down past the top of the content area, keep them at the heading
    if (contentCol) {
      var rect = contentCol.getBoundingClientRect();
      if (rect.top < 70) {
        var targetScroll = window.pageYOffset + rect.top - 85;
        window.scrollTo({ top: Math.max(0, targetScroll), behavior: 'smooth' });
      }
    }

    // 4. Close mobile off-canvas if open
    closeSidebar();
  }

  // Bind clicks on sidebar links
  sidebarLinks.forEach(function (link) {
    link.addEventListener('click', function (e) {
      e.preventDefault();
      var filter = this.getAttribute('data-filter');
      switchCategory(filter, true);
    });
  });

  // Bind clicks on "View Services →" inside All Categories grid
  document.addEventListener('click', function (e) {
    var viewBtn = e.target.closest('.btn-view-category-services');
    if (viewBtn) {
      e.preventDefault();
      var cat = viewBtn.getAttribute('data-category');
      if (cat) {
        switchCategory(cat, true);
      }
    }
  });

  // Browser Back/Forward navigation support
  window.addEventListener('popstate', function (e) {
    var state = e.state;
    var cat = (state && state.category) ? state.category : null;
    if (!cat) {
      var path = window.location.pathname;
      for (var slug in categoryUrls) {
        if (slug !== 'all' && path.indexOf(slug) !== -1) {
          cat = slug;
          break;
        }
      }
      if (!cat) cat = 'all';
    }
    switchCategory(cat, false);
  });

  /* ── Duplicate Cart Alert Toast helper ── */
  var _cartAlertTimer = null;
  function showCartDuplicateAlert() {
    var el = document.getElementById('cartDuplicateAlert');
    if (!el) return;
    el.style.display = 'block';
    el.style.opacity = '1';
    clearTimeout(_cartAlertTimer);
    _cartAlertTimer = setTimeout(function () {
      el.style.opacity = '0';
      setTimeout(function () { el.style.display = 'none'; }, 320);
    }, 2600);
  }

  /* ── Add to Cart Button Handler (with duplicate prevention) ── */
  document.addEventListener('click', function (e) {
    var cartBtn = e.target.closest('.btn-add-to-cart');
    if (!cartBtn) return;
    e.preventDefault();
    e.stopPropagation(); // Stop card click navigation

    var serviceId = cartBtn.getAttribute('data-service-id');
    if (!serviceId || serviceId === '0') return;

    // ── Duplicate check: scan current cart items in the DOM ──
    // We track added services in a Set so we don't need a server round-trip
    if (!window._refixelCartIds) window._refixelCartIds = new Set();
    if (window._refixelCartIds.has(serviceId)) {
      showCartDuplicateAlert();
      return;
    }

    var origHtml = cartBtn.innerHTML;
    cartBtn.disabled = true;
    cartBtn.innerHTML = '<i class="fa fa-spinner fa-spin"></i>';

    fetch('<?= \App\Core\View::url('/api/cart/add') ?>', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/x-www-form-urlencoded',
        'X-Requested-With': 'XMLHttpRequest'
      },
      body: 'service_id=' + encodeURIComponent(serviceId) + '&quantity=1'
    })
    .then(function (res) { return res.json(); })
    .then(function (data) {
      // Mark as added in our client-side set
      window._refixelCartIds.add(serviceId);

      cartBtn.innerHTML = '<i class="fa fa-check"></i>';
      cartBtn.style.background = '#3b82f6';
      cartBtn.style.borderColor = '#3b82f6';
      cartBtn.style.color = '#ffffff';

      if (window.syncCartUI) {
        window.syncCartUI();
      }

      setTimeout(function () {
        cartBtn.innerHTML = origHtml;
        cartBtn.style.background = '';
        cartBtn.style.borderColor = '';
        cartBtn.style.color = '';
        cartBtn.disabled = false;
      }, 1600);
    })
    .catch(function () {
      cartBtn.innerHTML = origHtml;
      cartBtn.disabled = false;
    });
  });

  /* ── Touch / Click anywhere on package card opens service details ── */
  document.addEventListener('click', function (e) {
    var card = e.target.closest('.service-package-card');
    if (!card) return;

    // Do nothing if clicked on Add to Cart, Book Now, or Details button directly
    if (e.target.closest('.btn-add-to-cart') || e.target.closest('.btn-package-book') || e.target.closest('.btn-package-details')) {
      return;
    }

    var serviceUrl = card.getAttribute('data-service-url');
    if (serviceUrl) {
      window.location.href = serviceUrl;
    }
  });

  /* ── Touch / Click anywhere on category card switches to category ── */
  document.addEventListener('click', function (e) {
    var catCard = e.target.closest('.service-cat-card');
    if (!catCard) return;

    if (e.target.closest('.btn-add-to-cart') || e.target.closest('.btn-view-category-services')) {
      return;
    }

    var item = catCard.closest('.service-card-item');
    if (item) {
      var cat = item.getAttribute('data-category');
      if (cat) switchCategory(cat, true);
    }
  });

  /* ── Desktop independent sidebar scroll isolation ── */
  var sidebarCard = document.querySelector('.services-sidebar-card');
  if (sidebarCard) {
    sidebarCard.addEventListener('wheel', function(e) {
      var scrollTop = this.scrollTop;
      var scrollHeight = this.scrollHeight;
      var height = this.clientHeight;
      var delta = e.deltaY;

      // Prevent scroll chaining to parent window/body
      if ((delta > 0 && scrollTop + height >= scrollHeight) || (delta < 0 && scrollTop <= 0)) {
        e.preventDefault();
      }
    }, { passive: false });
  }
});
</script>
