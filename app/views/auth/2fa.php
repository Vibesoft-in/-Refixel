<script>
function toggle2faMode() {
  const totpSection = document.getElementById('totpInputSection');
  const recoverySection = document.getElementById('recoveryInputSection');
  const toggleBtn = document.getElementById('toggleRecoveryBtn');
  const totpInput = document.getElementById('totpCodeInput');
  const recoveryInput = document.getElementById('recoveryCodeInput');

  if (totpSection.style.display === 'none') {
    totpSection.style.display = 'block';
    recoverySection.style.display = 'none';
    totpInput.required = true;
    recoveryInput.required = false;
    recoveryInput.value = '';
    totpInput.focus();
    toggleBtn.innerHTML = '<i class="fa fa-question-circle mr-1"></i> Cannot access authenticator? Use a recovery code';
  } else {
    totpSection.style.display = 'none';
    recoverySection.style.display = 'block';
    totpInput.required = false;
    totpInput.value = '';
    recoveryInput.required = true;
    recoveryInput.focus();
    toggleBtn.innerHTML = '<i class="fa fa-shield mr-1"></i> Use 6-digit authenticator code instead';
  }
}
</script>
